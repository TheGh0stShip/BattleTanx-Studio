"""Write the "supported by Studio" versus "implemented by the runtime" feature matrix as Markdown.

Every feature in ``core.runtime.FEATURES`` is something Studio can author,
validate and package.  Whether a runtime plays it is only known from a
runtime's declared capabilities (``btga-runtime.json``); without one, every
feature is "pending".

    python tools/runtime_feature_matrix.py docs/RUNTIME_FEATURES.md
    python tools/runtime_feature_matrix.py OUT.md --capabilities path/to/btga-runtime.json

The committed docs/RUNTIME_FEATURES.md is generated without capabilities;
a test checks it matches this tool's output, so the document cannot drift.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.btga_studio.core import runtime  # noqa: E402

GROUPS = (("map.", "Maps"), ("resource.", "Resources"), ("marker.", "Map records"), ("scenario", "Scenarios"), ("objective.", "Objectives"),
          ("trigger.", "Triggers"), ("condition.", "Victory and failure"), ("transition.", "Start and end transitions"),
          ("action.", "Actions (scenario triggers and item effects)"), ("item", "Items"), ("bot", "Bots and Queenlords"))


def matrix(capabilities: dict | None = None) -> str:
    declared = set((capabilities or {}).get("features") or [])
    name = None if capabilities is None else f"{capabilities['runtime']['name']} {capabilities['runtime']['version']}"
    lines = ["# Studio feature matrix", "",
             "Generated by `tools/runtime_feature_matrix.py`; do not edit by hand.", "",
             "\"Studio\" means Studio can author, validate, save and package the feature. \"Runtime\" is what a PC runtime "
             "declares in its `btga-runtime.json` capabilities file. " + (
                 f"This table was generated against {name}." if name else
                 "No runtime has declared capabilities yet, so every feature is **pending** in the runtime column: nothing "
                 "here may be described as playable until a runtime declares it."), ""]
    seen = set()
    for prefix, title in GROUPS:
        rows = [f for f in runtime.FEATURES if f.startswith(prefix) and f not in seen]
        if not rows:
            continue
        lines += [f"## {title}", "", "| Feature | What it is | Studio | Runtime |", "|---|---|---|---|"]
        for feature in rows:
            seen.add(feature)
            state = "pending" if capabilities is None else ("declared" if feature in declared else "**not declared**")
            lines.append(f"| `{feature}` | {runtime.FEATURES[feature]} | supported | {state} |")
        lines.append("")
    left = [f for f in runtime.FEATURES if f not in seen]
    if left:
        raise SystemExit(f"features without a group: {left}")
    return "\n".join(lines).rstrip() + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path)
    parser.add_argument("--capabilities", type=Path)
    args = parser.parse_args(argv)
    capabilities = json.loads(args.capabilities.read_text(encoding="utf-8")) if args.capabilities else None
    args.output.write_text(matrix(capabilities), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
